function [tempp1,tempp2,tempsx1,tempsx2]=crosslocal(y6,y9,t)
%----------插值角度数据--------------------------%
alfa09=-4.0434e-11*t^4+6.456268e-9*t^3-2.818831351e-6*t^2+7.25974671632e-4*t-0.656511680113381;
beta09=-3.719013e-9*t^3-4.32836150e-7*t^2+8.77544462434e-4*t+0.420379727436521;

alfa06=-1.6535e-11*t^4+9.09515e-10*t^3-1.609455535e-6*t^2+1.038044062134e-3*t+0.026929158385553;
beta06=-2.172e-11*t^4+1.337106e-9*t^3-2.267042195e-6*t^2+1.001815578095e-3*t+0.020219697876230;
