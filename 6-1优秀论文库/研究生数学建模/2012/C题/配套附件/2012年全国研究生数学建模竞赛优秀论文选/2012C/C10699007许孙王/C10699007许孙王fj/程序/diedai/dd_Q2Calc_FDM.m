    for j = 2 : n+1
        u(i+1,j) = kappa * (u(i,j+1) - 2*u(i,j) + u(i,j-1)) ...
                 + kappa * dt * c / 2.0 * (u(i,j+1) - u(i,j-1)) ...
                 + 2 * u(i,j) - u(i-1,j) - kappa * grav_prime * dt.^2;
    end
    u(i+1,1) = u(i+1,n+1);
    u(i+1,n+2) = u(i+1,2);
end

% 求解泵的载荷
